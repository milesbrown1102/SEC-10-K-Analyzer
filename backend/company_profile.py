# backend/company_profile.py
"""
One company, everything the app knows: what it does, how the stock has
done, which tracked funds bought it and roughly when (and at what prices),
insiders, connections to the mega-caps, the buy score, and a case for /
case against built from that evidence.

What this can't tell you, stated on the page too:
- WHEN a fund bought: a 13F only shows holdings at quarter end, so a new
  position was bought sometime during that quarter. The price range over
  that quarter is shown instead of a date.
- WHY a fund bought: funds don't disclose reasons. The "case for" lists
  the evidence visible in filings and prices, not the fund's motive.
- The case for / against is generated by fixed rules from the data. It's
  research input, not a recommendation.
"""

import re
import time
from datetime import timedelta
from typing import Dict, List, Optional

import requests

from . import (
    aftermath, bottleneck_detector, db, industry_radar, insider_trading, institutional_holdings,
    opportunities, point_in_time as pit, scoring, sec_utils,
)
from universal_section_extractor import extract_all_sections

PROFILE_VERSION = "v2"


def _plus(d: str, days: int) -> str:
    return (pit.datetime.fromisoformat(d) + timedelta(days=days)).date().isoformat()


def describe(cik: str, session: requests.Session) -> Optional[Dict]:
    """
    What the company says it does: the opening of Item 1 (Business) of its
    latest 10-K, or — for a company too new to have filed one (Cerebras,
    SpaceX) — the overview in its IPO prospectus.
    """
    f = pit.latest_10k(cik, pit.today(), session)
    prospectus = False
    if not f:
        f = next((x for x in pit.all_filings(cik, session)
                  if x["form"] in ("424B4", "424B1", "S-1/A", "S-1", "F-1", "F-1/A")), None)
        prospectus = True
    if not f:
        return None
    key = f"{cik}_{f['accession_number']}"
    cached = db.cache_get("company_description", key, ttl_seconds=None)
    if cached is not None:
        return cached
    text = sec_utils.fetch_filing_text(cik, f, session) or ""
    if prospectus:
        m = re.search(r"(?i)\n\s*(?:company\s+)?overview\s*\n", text)
        business = text[m.end():m.end() + 30000] if m else text[:60000]
    else:
        business = extract_all_sections(text, max_chars=60000).get("business", "")
    sentences = [s for s in bottleneck_detector._sentences(business)
                 if 80 <= len(s) <= 600 and re.search(r"(?i)\b(?:we|our|the company)\b", s)
                 and not re.search(r"(?i)forward-looking|table of contents|item\s+1", s)]
    out = {"summary": " ".join(sentences[:3]),
           "source": f"{'IPO prospectus' if prospectus else '10-K'} filed {f['filing_date']}",
           "url": sec_utils.get_filing_document_url(cik, f)}
    db.cache_set("company_description", key, out)
    return out


def _price_range(ticker: str, start: str, end: str) -> Optional[Dict]:
    hist = pit.price_history(ticker)
    closes = [(d, v["adj_close"]) for d, v in hist.items() if start < d <= end]
    if not closes:
        return None
    vals = [c for _, c in closes]
    first_trade = min(d for d, _ in closes)
    listed_during = min(hist) > start  # no prices before the window: listed during it
    return {"low": round(min(vals), 2), "high": round(max(vals), 2),
            "avg": round(sum(vals) / len(vals), 2),
            "first_trading_day": first_trade if listed_during else None}


def fund_activity(ticker: str) -> List[Dict]:
    """Tracked managers' latest-quarter moves in this stock, with the window and price range."""
    report = institutional_holdings.get_latest_report()
    if not report:
        return []
    now = pit.price_on(ticker, pit.today())
    out = []
    for m in report["managers"]:
        if m.get("error"):
            continue
        for c in m["changes"]:
            if (c.get("ticker") or "").upper() != ticker or c["put_call"]:
                continue
            rng = _price_range(ticker, m["prior_report_date"], m["report_date"])
            out.append({
                "manager": m["name"], "person": m.get("manager"), "style": m.get("style"),
                "change": c["change_type"], "shares_change_pct": c["shares_change_pct"],
                "weight_pct": c["weight_curr_pct"], "value": c["value_curr"],
                "window_start": m["prior_report_date"], "window_end": m["report_date"],
                "filed": m.get("filing_date"), "price_range": rng,
                "since_avg_pct": round((now / rng["avg"] - 1) * 100, 1) if now and rng else None,
            })
    order = {"new": 0, "added": 1, "held": 2, "trimmed": 3, "exited": 4}
    out.sort(key=lambda r: (order.get(r["change"], 9), -(r["value"] or 0)))
    return out


def connections(ticker: str, cik: str, session: requests.Session) -> Dict:
    """Mega-caps that invested in / signed with it (Opportunities report) and its own recent deals."""
    opp = opportunities.get_latest_report() or {}
    giants = [g for g in opp.get("giants_money", []) if (g.get("ticker") or "").upper() == ticker]
    end = pit.today()
    own = aftermath.own_deals(cik, _plus(end, -365), end, session)
    return {"giants": giants, "own_deals": own}


def radar_hits(ticker: str) -> Dict:
    report = industry_radar.get_latest_report() or {}
    out = {}
    for side in ("seller", "buyer"):
        for c in report.get(side, {}).get("companies", []):
            if (c.get("ticker") or "").upper() == ticker:
                out[side] = {"phrases": c["phrases"], "new": c["new"], "url": c["url"]}
    return out


def build_case(p: Dict) -> Dict:
    """
    Pure function. Bullet points for and against, from the profile's data.
    Each bullet cites the number it rests on; nothing is inferred beyond it.
    """
    pro, con = [], []
    v, t, ins = p.get("valuation") or {}, p.get("tightness") or {}, p.get("insider") or {}
    stock, funds = p.get("stock") or {}, p.get("funds") or []
    rev_q = p.get("quarterly_revenue_growth_pct")

    if rev_q is not None:
        if rev_q >= 25:
            pro.append(f"Revenue is growing fast: latest quarter {rev_q:+.0f}% vs a year earlier.")
        elif rev_q < 0:
            con.append(f"Revenue is shrinking: latest quarter {rev_q:+.0f}% vs a year earlier.")
    if t.get("mentions"):
        pro.append(f"Its own latest filing describes tight supply or pricing power "
                   f"({t['mentions']} passages), e.g. “{t['evidence'][0][:180]}…”")
    radar = p.get("radar") or {}
    if radar.get("seller", {}).get("new"):
        pro.append("It newly started using scarcity language this year (“"
                   + "”, “".join(radar["seller"]["phrases"][:2]) + "”).")
    gasy = v.get("growth_adjusted_sales_yield")
    if gasy is not None:
        if gasy >= scoring.VALUATION_FULL_AT:
            pro.append(f"Reasonably priced for its growth (price/sales {1 / v['sales_yield']:.1f}x with "
                       f"{v['revenue_growth_annual']:+.0f}% annual revenue growth).")
        elif gasy < scoring.VALUATION_HALF_AT:
            con.append(f"Expensive for its growth (price/sales {1 / v['sales_yield']:.1f}x with "
                       f"{v['revenue_growth_annual']:+.0f}% annual revenue growth).")
    elif v.get("revenue_growth_annual") is not None and v["revenue_growth_annual"] <= 0:
        con.append(f"Annual revenue fell {v['revenue_growth_annual']:.0f}% in its last fiscal year.")
    if v.get("earnings_yield") is not None and v["earnings_yield"] < 0:
        con.append("Not profitable in its last fiscal year.")
    elif v.get("earnings_yield"):
        pe = 1 / v["earnings_yield"]
        if pe > 60:
            con.append(f"High earnings multiple: about {pe:.0f}x last year's earnings.")
    buyers = [f for f in funds if f["change"] in ("new", "added")]
    sellers = [f for f in funds if f["change"] in ("trimmed", "exited")]
    if buyers:
        pro.append(f"{len(buyers)} tracked fund(s) bought or added last quarter: "
                   + ", ".join(f["manager"] for f in buyers[:4]) + ".")
        b = buyers[0]
        rng, since = b.get("price_range"), b.get("since_avg_pct")
        if rng and since is not None:
            line = (f"They bought between {b['window_start']} and {b['window_end']}, when it traded "
                    f"${rng['low']:,.0f}–${rng['high']:,.0f} (about ${rng['avg']:,.0f} on average); "
                    f"it's {since:+.0f}% from that average now.")
            if rng.get("first_trading_day"):
                line += f" It only began trading on {rng['first_trading_day']}, so they bought at or after the IPO."
            (pro if since >= -10 else con).append(line)
    if len(sellers) > len(buyers):
        con.append(f"More tracked funds sold ({len(sellers)}) than bought ({len(buyers)}) last quarter.")
    if ins.get("discretionary_buyers"):
        pro.append(f"{ins['discretionary_buyers']} insider(s) bought shares with their own money in the last "
                   f"90 days (${ins['total_value']:,.0f}).")
    for g in (p.get("connections") or {}).get("giants", []):
        if g["relationship"] == "invested":
            pro.append(f"{g['giant']} invested in it"
                       + (f" (${g['amount_usd'] / 1e9:,.2f}B)" if g.get("amount_usd") else "") + f", {g['date']}.")
    if stock.get("above_200sma") is False:
        con.append("The stock is below its 200-day average (downtrend).")
    elif stock.get("above_200sma"):
        pro.append("The stock is above its 200-day average (uptrend).")
    r1 = stock.get("return_1y_pct")
    if r1 is not None and r1 > 150:
        con.append(f"Already up {r1:.0f}% in a year: much of the good news may be priced in.")
    if (v.get("market_cap") or 0) and v["market_cap"] < 2e9:
        con.append("Small company (under $2B): bigger swings and higher risk of dilution.")
    return {"for": pro, "against": con}


def build_profile(ticker: str, session: Optional[requests.Session] = None) -> Dict:
    ticker = ticker.strip().upper()
    cached = db.cache_get("company_profile_full", f"{PROFILE_VERSION}|{ticker}", ttl_seconds=6 * 3600)
    if cached is not None:
        return cached
    session = session or sec_utils.make_sec_session()
    cik = sec_utils.get_cik_for_ticker(ticker, session)
    if not cik:
        return {"error": f"No SEC filer found for '{ticker}'"}
    today = pit.today()
    prof = aftermath.company_profile(cik, session)
    tech = pit.technicals(ticker, today)
    year_ago = _plus(today, -365)
    p0 = pit.price_on(ticker, year_ago)
    spy0, spy1 = pit.price_on("SPY", year_ago), pit.price_on("SPY", today)
    try:
        insider_trading.refresh_recent([ticker], session)
    except Exception:
        pass
    p = {
        "ticker": ticker, "cik": cik, "name": prof.get("name"), "industry": prof.get("industry"),
        "sic": prof.get("sic"),
        "description": describe(cik, session),
        "stock": {
            "price": tech["price"], "above_200sma": tech["above_200sma"],
            "return_1y_pct": round((tech["price"] / p0 - 1) * 100, 1) if tech["price"] and p0 else None,
            "spy_1y_pct": round((spy1 / spy0 - 1) * 100, 1) if spy0 and spy1 else None,
        },
        "valuation": pit.valuation(ticker, today, session),
        "quarterly_revenue_growth_pct": pit.quarterly_revenue_yoy(cik, today, session),
        "tightness": bottleneck_detector.supplier_tightness(ticker, today, session),
        "insider": {k: v for k, v in insider_trading.insider_activity(cik, today).items()},
        "insider_year": insider_trading.insider_activity(cik, today, 365),
        "funds": fund_activity(ticker),
        "connections": connections(ticker, cik, session),
        "radar": radar_hits(ticker),
        "generated_at": time.time(),
    }
    market = {"relative_volume": tech["relative_volume"], "above_200sma": tech["above_200sma"],
              "quarterly_revenue_growth_pct": p["quarterly_revenue_growth_pct"]}
    p["score"] = scoring.compute_buy_score(
        ticker=ticker, thesis_intact=False, signal_confidence=0.0, market_data=market,
        confirmed_deal=False, valuation=p["valuation"], own_tightness=p["tightness"], insider=p["insider"])
    p["case"] = build_case(p)
    db.cache_set("company_profile_full", f"{PROFILE_VERSION}|{ticker}", p)
    return p
